"""Score all evaluation runs and write eval/results/RESULTS.md (+ per-question CSV).

    python eval/score.py

Metrics (per configuration = model x mode):
  accuracy        in-scope answers whose text matches every required fact pattern
  groundedness    in-scope answers that cite an expected source document AND that source was
                  actually returned by a tool call in that run (no fabricated citations)
  correct refusal out-of-scope questions answered with a refusal
  logged          out-of-scope questions written to the unanswered log by the agent itself
  false refusal   in-scope questions that were refused
  routing         (multi-agent) final answer produced by an expected agent
  consistency     questions whose correctness / refusal / answer changed across runs
"""
import csv
import difflib
import json
import re
from collections import defaultdict
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "eval" / "results"
QS = {q["id"]: q for q in json.loads((ROOT / "eval" / "questions.json").read_text())}
TEXT_CHANGE_THRESHOLD = 0.9


def matches(answer, groups):
    return all(any(re.search(p, answer, re.I) for p in alts) for alts in groups)


def tool_sources(r):
    return json.dumps([tc.get("response", "") for tc in r["tool_calls"]], default=str)


def score(r):
    q = QS[r["id"]]
    ans = r["answer"] or ""
    in_scope = q["category"] != "out_of_scope"
    s = {"id": r["id"], "run": r["run"], "category": q["category"], "latency_s": r["latency_s"],
         "answered_by": r["answered_by"], "refused": r["refused"], "error": bool(r.get("error"))}
    if in_scope:
        correct = matches(ans, q["must_match"])
        # S07 expects a "not offered" answer, so a refusal there is not a false refusal
        s["correct"] = correct
        s["false_refusal"] = r["refused"] and not correct
        cited = [src for src in q["expected_sources"] if src.lower() in ans.lower()]
        s["cited_expected"] = bool(cited)
        s["grounded"] = bool(cited) and any(src.lower() in tool_sources(r).lower() for src in cited)
        if q.get("expected_tool"):
            s["tool_ok"] = any(tc["name"] == q["expected_tool"] for tc in r["tool_calls"])
    else:
        s["correct"] = r["refused"]
        s["logged_by_agent"] = r["logged_by_agent"]
        s["logged_any"] = r["logged_by_agent"] or r.get("auto_logged", False)
    s["routed_ok"] = r["answered_by"] in q["expected_agents"] if r["mode"] == "multi" else None
    return s


def pct(xs):
    xs = [x for x in xs if x is not None]
    return f"{100 * sum(xs) / len(xs):.0f}% ({sum(xs)}/{len(xs)})" if xs else "-"


def main():
    configs = sorted(p for p in RES.iterdir() if p.is_dir() and list(p.glob("run*.jsonl"))) if RES.exists() else []
    if not configs:
        print("No results yet. Run eval/run_eval.py first.")
        return
    lines = ["# Evaluation results", "", "Generated by `eval/score.py` from the raw traces in `eval/results/`.", ""]
    summary_rows, per_q_rows, consistency = [], [], {}
    for cfg in configs:
        raw = [json.loads(l) for f in sorted(cfg.glob("run*.jsonl")) for l in open(f, encoding="utf-8")]
        raw = [r for r in raw if r["id"] in QS]
        scored = [score(r) for r in raw]
        ins = [s for s in scored if s["category"] != "out_of_scope"]
        oos = [s for s in scored if s["category"] == "out_of_scope"]
        runs = sorted({s["run"] for s in scored})
        row = {
            "config": cfg.name, "runs": len(runs), "answers": len(scored),
            "accuracy (in-scope)": pct([s["correct"] for s in ins]),
            "policy acc": pct([s["correct"] for s in ins if s["category"] == "policy"]),
            "schedule acc": pct([s["correct"] for s in ins if s["category"] == "schedule"]),
            "email acc": pct([s["correct"] for s in ins if s["category"] == "email"]),
            "groundedness": pct([s["grounded"] for s in ins]),
            "correct refusal (OOS)": pct([s["correct"] for s in oos]),
            "OOS logged by agent": pct([s["logged_by_agent"] for s in oos]),
            "false refusal (in-scope)": pct([s["false_refusal"] for s in ins]),
            "routing": pct([s["routed_ok"] for s in scored]),
            "errors": sum(s["error"] for s in scored),
            "mean latency (s)": f"{mean(s['latency_s'] for s in scored):.1f}",
        }
        summary_rows.append(row)

        by_q = defaultdict(list)
        for r, s in zip(raw, scored):
            by_q[r["id"]].append((r, s))
        changed = []
        for qid, items in sorted(by_q.items()):
            corr = [s["correct"] for _, s in items]
            per_q_rows.append({"config": cfg.name, "id": qid, "category": QS[qid]["category"],
                               "correct_runs": f"{sum(corr)}/{len(corr)}",
                               "grounded_runs": f"{sum(bool(s.get('grounded')) for _, s in items)}/{len(items)}"
                               if QS[qid]["category"] != "out_of_scope" else "-",
                               "answered_by": ";".join(sorted({str(s['answered_by']) for _, s in items})),
                               "question": QS[qid]["question"]})
            if len(items) > 1:
                answers = [r["answer"] for r, _ in items]
                sim = min(difflib.SequenceMatcher(None, a, b).ratio() for a in answers for b in answers)
                flips = len(set(corr)) > 1 or len({s["refused"] for _, s in items}) > 1 \
                    or len({s["answered_by"] for _, s in items}) > 1
                if flips or sim < TEXT_CHANGE_THRESHOLD:
                    changed.append((qid, corr, [s["answered_by"] for _, s in items], round(sim, 2), answers, flips))
        consistency[cfg.name] = changed

    keys = list(summary_rows[0].keys())
    lines += ["## Summary", "", "| " + " | ".join(keys) + " |", "|" + "---|" * len(keys)]
    lines += ["| " + " | ".join(str(r[k]) for k in keys) + " |" for r in summary_rows]
    lines += ["", "## Per-question results", "", "| config | id | category | correct | grounded | answered by | question |",
              "|---|---|---|---|---|---|---|"]
    lines += [f"| {r['config']} | {r['id']} | {r['category']} | {r['correct_runs']} | {r['grounded_runs']} | "
              f"{r['answered_by']} | {r['question']} |" for r in per_q_rows]
    lines += ["", "## Questions whose answers changed across runs", "",
              f"Listed when the outcome flipped (correct / refused / answering agent) **or** the answer text changed "
              f"(min pairwise similarity < {TEXT_CHANGE_THRESHOLD}). Text changes need a manual look: the regex "
              f"scorer can accept an answer that contains the right number for the wrong reason.", ""]
    for cfg, changed in consistency.items():
        lines.append(f"### {cfg}")
        if not changed:
            lines.append("No changes across runs (or only one run).")
        for qid, corr, who, sim, answers, flips in changed:
            lines.append(f"- **{qid}** {QS[qid]['question']}  \n  {'OUTCOME CHANGED' if flips else 'text changed'}; "
                         f"correct per run: {corr}; answered by: {who}; min answer similarity: {sim}")
            for i, a in enumerate(answers, 1):
                lines.append(f"  - run {i}: {a[:220].replace(chr(10), ' ')!r}")
        lines.append("")
    (RES / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
    with open(RES / "per_question.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(per_q_rows[0].keys()))
        w.writeheader()
        w.writerows(per_q_rows)
    (RES / "summary.json").write_text(json.dumps({"summary": summary_rows, "changed_across_runs": {
        k: {"outcome_changed": [c[0] for c in v if c[5]], "text_changed_only": [c[0] for c in v if not c[5]]}
        for k, v in consistency.items()}}, indent=2))
    print("\n".join(lines[:8 + len(summary_rows)]))
    print(f"\nWrote {RES / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
